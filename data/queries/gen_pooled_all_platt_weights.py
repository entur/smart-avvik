#!/usr/bin/env python3
"""Generate create_pooled_all_platt_weights.sql.

Flattens every operator-aware Platt model in the _pooled_all family (9 heads x 5 ask-horizon
buckets = 45 LOGISTIC_REG models) into one small lookup table
  disruptions.pooled_all_platt_weights(head, lead_bucket, operator, b, a, w)
so predict_calls_bus.sql can apply the calibration closed form
  p_cal = sigmoid(b + a*raw_logit + w[operator])
with a single JOIN on (head, lead_bucket, operator) instead of 45 inline ML.WEIGHTS blocks.

b = __INTERCEPT__ weight, a = raw_logit weight, w = per-operator category_weights intercept.
A synthetic operator='*' row (w=0) is emitted per (head, bucket) as an unseen-operator fallback.

Re-run this AND the resulting SQL after any _pooled_all head/platt retrain (the weights table is a
materialized snapshot; serving reads the table, not ML.WEIGHTS live). Regenerate with:
    python data/queries/gen_pooled_all_platt_weights.py > data/queries/create_pooled_all_platt_weights.sql
"""

HEADS = [
    "cancel",
    "arr_ge5", "arr_ge10", "arr_ge20", "arr_ge40",
    "dep_ge5", "dep_ge10", "dep_ge20", "dep_ge40",
]
# (lead_bucket label, model-name infix)
BUCKETS = [("30", ""), ("60", "_lead60"), ("120", "_lead120"), ("240", "_lead240"), ("plan", "_plan")]
DS = "ent-kixavvik-dev.disruptions"
# The bus/GOA operators served live (matches predict_calls_bus.sql + bus_calls_planned_today.sql).
# A row is emitted for EVERY served operator per (head, bucket) so the serving inner-join always
# hits: a small operator with no rows at a far horizon simply gets w=0 (the shared scalar, no
# operator shift) instead of dropping the call. '*' is the same-shape fallback for any other code.
SERVED_OPERATORS = ["GOA", "RUT", "KOL", "SOF", "NOR", "SKY", "ATB", "OST", "FIN", "MOR", "TRO", "GCO", "*"]


def model_name(head: str, infix: str) -> str:
    return f"{head}_platt{infix}_pooled_all"


def cte_alias(head: str, bucket: str) -> str:
    return f"w_{head}_{bucket}"


def main() -> None:
    ops_sql = ", ".join(f"'{o}'" for o in SERVED_OPERATORS)
    ctes = []
    blocks = []
    for head in HEADS:
        for bucket, infix in BUCKETS:
            mdl = model_name(head, infix)
            alias = cte_alias(head, bucket)
            ctes.append(f"{alias} AS (SELECT * FROM ML.WEIGHTS(MODEL `{DS}.{mdl}`))")
            # one row per SERVED operator: model scalar (b, a) + that operator's intercept w
            # (0 when the operator has no fitted intercept at this head/horizon).
            blocks.append(
                f"SELECT '{head}' AS head, '{bucket}' AS lead_bucket, op AS operator,\n"
                f"  (SELECT weight FROM {alias} WHERE processed_input='__INTERCEPT__') AS b,\n"
                f"  (SELECT weight FROM {alias} WHERE processed_input='raw_logit') AS a,\n"
                f"  IFNULL((SELECT cw.weight FROM {alias} AS m2, UNNEST(m2.category_weights) AS cw\n"
                f"          WHERE m2.processed_input='operator' AND cw.category = op), 0) AS w\n"
                f"FROM UNNEST([{ops_sql}]) AS op"
            )

    header = (
        "-- Flattened operator-aware Platt weights for the _pooled_all serving path.\n"
        "-- GENERATED by data/queries/gen_pooled_all_platt_weights.py -- DO NOT EDIT BY HAND.\n"
        "-- 9 heads x 5 ask-horizon buckets = 45 LOGISTIC_REG platts -> one lookup table keyed\n"
        "-- (head, lead_bucket, operator) with the closed-form coefficients (b, a, w). Serving\n"
        "-- (predict_calls_bus.sql) applies sigmoid(b + a*raw_logit + w[operator]). The '*' rows are\n"
        "-- the unseen-operator fallback (w=0). Rebuild after any _pooled_all platt refit.\n"
    )
    body = (
        f"CREATE OR REPLACE TABLE `{DS}.pooled_all_platt_weights` AS\n"
        "WITH\n"
        + ",\n".join(ctes)
        + "\n"
        + "\nUNION ALL\n".join(blocks)
        + ";\n"
    )
    print(header + body)


if __name__ == "__main__":
    main()
