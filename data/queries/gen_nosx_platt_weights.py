"""Generate create_nosx_platt_weights.sql.

Flattens the no-SX Platt family (9 heads x 5 ask-horizon buckets = 45 LOGISTIC_REG models, from
create_cancel_calibration.sql / create_exceedance_calibration.sql / create_leadtime_calibration.sql)
into one small lookup table
  disruptions.nosx_platt_weights(head, lead_bucket, b, a)
so predict_calls_nosx.sql can apply the calibration closed form
  p_cal = sigmoid(b + a*raw_logit)
with a single JOIN on (head, lead_bucket) instead of 45 inline ML.WEIGHTS blocks.

Why a table here when predict_calls.sql reads ML.WEIGHTS live: the flagged path's 45 blocks are
already written and load-bearing, and rewriting them to reach a second population would put the
production alerting path at risk for a cosmetic win. The bus family (gen_pooled_all_platt_weights.py)
already established the table shape, so the no-SX path follows it and the flagged path is not
touched at all. The cost is the one this pattern always has, and it is stated in the generated
header too: the table is a SNAPSHOT. A platt refit that does not rebuild it leaves serving on the
old coefficients, silently.

THE SLOPE IS CLAMPED AT ZERO, and only on this side. A negative Platt slope says the model is
ANTI-informative -- a higher raw score becoming a lower calibrated probability -- and serving one
would invert the head's own ranking. Measured 2026-08-20, three of the 45 no-SX layers came back at
or below 0.21 and one below zero (cancel/plan a = -0.0445, cancel/240 0.100, cancel/120 0.202),
against 0.60-1.12 across the whole flagged family. That is not a real inversion, it is a fit with
nothing to fit: at a long horizon a no-SX call has neither situation features NOR observable state
(`plan` zeroes own_prev_delay and line_now_*), so the head is left with the line, the stop and the
hour, and its score barely moves with the outcome. Clamping to 0 makes the layer serve its intercept
alone -- the population's base rate at that horizon, which is exactly what "no information" should
produce, and a value that will never clear the alert gate. The intercept is NOT refit under the
clamp; at a slope this near zero it already carries essentially all of the fit.

Re-run this AND the resulting SQL after any no-SX platt refit, and look at the clamped layers when
you do: a slope that climbs off zero means a horizon has become informative, and one that goes
negative on a head that used to be healthy means something is wrong upstream, not merely thin.
Regenerate with:
    python data/queries/gen_nosx_platt_weights.py > data/queries/create_nosx_platt_weights.sql
"""

HEADS = [
    "cancel",
    "arr_ge5", "arr_ge10", "arr_ge20", "arr_ge40",
    "dep_ge5", "dep_ge10", "dep_ge20", "dep_ge40",
]
# (lead_bucket label, model-name suffix after the shared `_platt_nosx` stem). The 30-min bucket is
# the training anchoring and its layer carries no suffix, exactly as on the flagged side.
BUCKETS = [("30", ""), ("60", "_lead60"), ("120", "_lead120"), ("240", "_lead240"), ("plan", "_plan")]
DS = "ent-smartavvik-dev.disruptions"


def main() -> None:
    ctes, blocks = [], []
    for head in HEADS:
        for bucket, suffix in BUCKETS:
            alias = f"w_{head}_{bucket}"
            ctes.append(f"{alias} AS (SELECT * FROM ML.WEIGHTS(MODEL `{DS}.{head}_platt_nosx{suffix}`))")
            blocks.append(
                f"SELECT '{head}' AS head, '{bucket}' AS lead_bucket,\n"
                f"  (SELECT weight FROM {alias} WHERE processed_input='__INTERCEPT__') AS b,\n"
                f"  GREATEST((SELECT weight FROM {alias} WHERE processed_input='raw_logit'), 0) AS a"
            )

    header = (
        "-- Flattened Platt weights for the NO-SX serving path (calls no situation named).\n"
        "-- GENERATED by data/queries/gen_nosx_platt_weights.py -- DO NOT EDIT BY HAND.\n"
        "-- 9 heads x 5 ask-horizon buckets = 45 LOGISTIC_REG platts -> one lookup table keyed\n"
        "-- (head, lead_bucket) with the closed-form coefficients (b, a). Serving\n"
        "-- (predict_calls_nosx.sql) applies sigmoid(b + a*raw_logit).\n"
        "--\n"
        "-- THIS TABLE IS A SNAPSHOT, unlike the flagged path's inline ML.WEIGHTS blocks, which read\n"
        "-- live. Rebuild it after ANY no-SX platt refit or head retrain -- a stale table does not\n"
        "-- error, it just serves last quarter's calibration on a population whose base rate moves\n"
        "-- seasonally. 45 rows; the rebuild costs nothing.\n"
    )
    body = (
        f"CREATE OR REPLACE TABLE `{DS}.nosx_platt_weights` AS\n"
        "WITH\n"
        + ",\n".join(ctes)
        + "\n"
        + "\nUNION ALL\n".join(blocks)
        + ";\n"
    )
    print(header + body)


if __name__ == "__main__":
    main()
