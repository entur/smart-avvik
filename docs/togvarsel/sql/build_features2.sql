),
wx AS (
  SELECT d, MIN(t) wx_tmin, MAX(t) wx_tmax, MAX(snow) wx_snow, SUM(precip) wx_precip, MAX(wind) wx_wind,
    MIN(IF(h<=6, t, NULL)) wx_tmin_night, SUM(IF(h<=6, precip, 0)) wx_precip_night, MAX(IF(h<=6, snow, NULL)) wx_snow_night, COUNT(*) wx_n_h
  FROM hourly GROUP BY d
)
SELECT f.d, et.* EXCEPT(d), sxc.* EXCEPT(d), wx.* EXCEPT(d)
FROM `ent-kixavvik-dev.disruptions.togvarsel_days` f
LEFT JOIN et USING (d) LEFT JOIN sxc USING (d) LEFT JOIN wx USING (d)
